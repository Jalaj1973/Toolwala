// Icon Mapping Function
export function getToolSvgIcon(iconName, size = 24) {
  const map = {
    'merge': IconMerge,
    'split': IconSplit,
    'compress': IconCompress,
    'rotate': IconRotate,
    'reorder': IconGrid,
    'extract': IconTrim,
    'watermark': IconWatermark,
    'lock': IconLock,
    'unlock': IconUnlock,
    'convert': IconConvert,
    'resize': IconResize,
    'crop': IconCrop,
    'flip': IconFlip,
    'speed': IconSpeed,
    'volume': IconVolume,
    'mute': IconMute,
    'pdf': IconPdf,
    'image': IconImage,
    'video': IconVideo,
    'audio': IconAudio,
    'document': IconDocument,
    'archive': IconArchive,
    'folder': IconFolder,
    'sparkles': IconSparkles,
  };

  const Component = map[iconName] || map['convert'];
  return <Component size={size} />;
}
